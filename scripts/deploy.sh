#!/usr/bin/env bash
#
# deploy-creative-studio.sh
#
# One-file deployment for GenMedia Creative Studio (vertex-ai-creative-studio).
# Implements the documented flow end to end:
#   https://googlecloudplatform.github.io/vertex-ai-creative-studio/core/installation/deploy/
#
#   1. preflight  : tool / auth / project / billing checks
#   2. bootstrap  : enable the APIs Terraform itself needs to call
#   3. source     : clone (or reuse / update) the upstream repository
#   4. terraform  : write terraform.tfvars, init, apply
#   5. dns        : (custom-domain mode) wait for the A record -> LB IP
#   6. build      : submit Cloud Build, which builds the image and rolls Cloud Run
#   7. iap        : (Cloud Run-domain mode) grant the initial user IAP access
#   8. cert       : (custom-domain mode) wait for the managed certificate to go ACTIVE
#
# Safe to re-run: every step is idempotent.
#
# Usage:   ./deploy-creative-studio.sh --project-id my-proj --initial-user me@example.com
#          ./deploy-creative-studio.sh --help
#
set -euo pipefail

readonly SCRIPT_NAME="${0##*/}"
readonly REPO_URL="https://github.com/GoogleCloudPlatform/vertex-ai-creative-studio.git"
readonly SERVICE_NAME="creative-studio"

# ---------------------------------------------------------------------------
# Defaults (every one is overridable by env var or flag)
# ---------------------------------------------------------------------------
# This script lives at the root of the checkout it deploys, so paths anchor to
# the script's own directory — not $PWD, which would break when invoked from
# anywhere else.
SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"

PROJECT_ID="${PROJECT_ID:-}"
REGION="${REGION:-us-central1}"
INITIAL_USER="${INITIAL_USER:-}"
DOMAIN_NAME="${DOMAIN_NAME:-}"
SRC_DIR="${SRC_DIR:-$SCRIPT_DIR}"
GIT_REF="${GIT_REF:-}"
URL_FILE="${URL_FILE:-$SCRIPT_DIR/creative-studio-url.txt}"

ASSUME_YES=0
SKIP_CLONE=0
SKIP_TERRAFORM=0
SKIP_BUILD=0
SKIP_DNS_WAIT=0
SKIP_CERT_WAIT=0
DRY_RUN=0
DESTROY=0
ADD_USER=""
DNS_TIMEOUT="${DNS_TIMEOUT:-1800}"   # 30 min for the A record to propagate
CERT_TIMEOUT="${CERT_TIMEOUT:-3600}" # up to 60 min for a Google-managed cert
EXTRA_TFVARS=()

# ---------------------------------------------------------------------------
# Output helpers
# ---------------------------------------------------------------------------
if [[ -t 1 ]] && [[ -z "${NO_COLOR:-}" ]]; then
  C_RESET=$'\033[0m'; C_RED=$'\033[31m'; C_GREEN=$'\033[32m'
  C_YELLOW=$'\033[33m'; C_BLUE=$'\033[34m'; C_BOLD=$'\033[1m'
else
  C_RESET=""; C_RED=""; C_GREEN=""; C_YELLOW=""; C_BLUE=""; C_BOLD=""
fi

log()   { printf '%s[%s]%s %s\n' "$C_BLUE"   "$(date +%H:%M:%S)" "$C_RESET" "$*"; }
ok()    { printf '%s  ✓%s %s\n'  "$C_GREEN"  "$C_RESET" "$*"; }
warn()  { printf '%s  !%s %s\n'  "$C_YELLOW" "$C_RESET" "$*" >&2; }
err()   { printf '%s  ✗%s %s\n'  "$C_RED"    "$C_RESET" "$*" >&2; }
die()   { err "$*"; exit 1; }
step()  { printf '\n%s==> %s%s\n' "$C_BOLD" "$*" "$C_RESET"; }

# Echo a command, then run it (or just echo it under --dry-run).
run() {
  printf '%s    $ %s%s\n' "$C_BLUE" "$*" "$C_RESET"
  (( DRY_RUN )) && return 0
  "$@"
}

# Same, but from a directory. Under --dry-run the directory may not exist yet
# (nothing was cloned), so never attempt the cd.
run_in() {
  local dir="$1"; shift
  printf '%s    $ (cd %s && %s)%s\n' "$C_BLUE" "$dir" "$*" "$C_RESET"
  (( DRY_RUN )) && return 0
  ( cd "$dir" && "$@" )
}

confirm() {
  local prompt="$1" reply
  (( ASSUME_YES )) && return 0
  if [[ ! -t 0 ]] && [[ ! -r /dev/tty ]]; then
    die "'$prompt' needs confirmation but there is no terminal. Re-run with --yes."
  fi
  read -r -p "$prompt [y/N] " reply < /dev/tty || true
  [[ "$reply" =~ ^[Yy]$ ]]
}

